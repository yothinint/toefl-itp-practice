#!/usr/bin/env python3
"""Build data.js and the Section 1 listening audio from tools/exam.json.

Uses macOS `say` for speech and `afconvert` for AAC encoding, so it must run on a Mac.
Usage: python3 tools/build.py
"""
import json
import os
import subprocess
import tempfile
import wave

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RATE = 22050
VOICES = {"N": "Daniel", "W": "Samantha", "M": "Reed (อังกฤษ (สหรัฐฯ))"}
SPEED = 160  # words per minute, close to recorded TOEFL pace
ANSWER_GAP = 12.0  # seconds to answer after each question, as in the paper test

tmp = tempfile.mkdtemp()
frames = []  # list of bytes chunks
pos = [0]  # samples written


def now():
    return round(pos[0] / RATE, 2)


def silence(sec):
    n = int(sec * RATE)
    frames.append(b"\x00\x00" * n)
    pos[0] += n


def speak(who, text):
    path = os.path.join(tmp, f"u{len(frames)}.wav")
    subprocess.run(["say", "-v", VOICES[who], "-r", str(SPEED), "-o", path,
                    "--data-format=LEI16@%d" % RATE, text], check=True)
    with wave.open(path) as w:
        data = w.readframes(w.getnframes())
    frames.append(data)
    pos[0] += len(data) // 2


def dialogue(lines, gap=0.5):
    for i, (who, text) in enumerate(lines):
        if i:
            silence(gap)
        speak(who, text)


exam = json.load(open(os.path.join(ROOT, "tools", "exam.json"), encoding="utf-8"))
listening = exam["sections"][0]
cues = {"parts": {}, "questions": [], "talks": {}}
qno = 0

silence(0.8)
speak("N", listening["intro"])
silence(1.5)
for part in listening["parts"]:
    cues["parts"][part["id"]] = now()
    speak("N", part["directions"])
    silence(1.5)
    if part["id"] == "A":
        for q in part["questions"]:
            qno += 1
            start = now()
            speak("N", f"Number {qno}.")
            silence(0.6)
            dialogue(q["script"])
            silence(0.7)
            ask = now()
            speak("N", q["ask"])
            ask_end = now()
            silence(ANSWER_GAP)
            cues["questions"].append({"q": qno, "part": "A", "start": start, "ask": ask,
                                      "askEnd": ask_end, "end": now()})
    else:
        speak("N", part["intro"])
        silence(1.0)
        talk_start = now()
        dialogue(part["script"], gap=0.6)
        cues["talks"][part["id"]] = {"start": talk_start, "end": now()}
        silence(1.5)
        speak("N", "Now get ready to answer the questions.")
        silence(1.2)
        for q in part["questions"]:
            qno += 1
            start = now()
            speak("N", f"Question {qno}. {q['ask']}")
            ask_end = now()
            silence(ANSWER_GAP)
            cues["questions"].append({"q": qno, "part": part["id"], "start": start, "ask": start,
                                      "askEnd": ask_end, "end": now()})
    silence(1.0)
cues["outro"] = now()
speak("N", listening["outro"])
silence(1.0)
cues["duration"] = now()

os.makedirs(os.path.join(ROOT, "audio"), exist_ok=True)
wav_path = os.path.join(tmp, "section1.wav")
with wave.open(wav_path, "wb") as w:
    w.setnchannels(1)
    w.setsampwidth(2)
    w.setframerate(RATE)
    for chunk in frames:
        w.writeframes(chunk)
out = os.path.join(ROOT, "audio", "section1.m4a")
subprocess.run(["afconvert", "-f", "m4af", "-d", "aac", "-b", "48000", wav_path, out], check=True)

check = os.path.join(tmp, "soundcheck.aiff")
subprocess.run(["say", "-v", VOICES["N"], "-r", str(SPEED), "-o", check,
                "This is a sound check. If you can hear this clearly, you are ready to begin."], check=True)
subprocess.run(["afconvert", "-f", "m4af", "-d", "aac", "-b", "48000", check,
                os.path.join(ROOT, "audio", "soundcheck.m4a")], check=True)

exam["listeningAudio"] = "audio/section1.m4a"
exam["soundCheck"] = "audio/soundcheck.m4a"
exam["cues"] = cues
with open(os.path.join(ROOT, "data.js"), "w", encoding="utf-8") as f:
    f.write("// Generated by tools/build.py from tools/exam.json. Do not edit by hand.\n")
    f.write("window.EXAM = ")
    json.dump(exam, f, ensure_ascii=False, indent=1)
    f.write(";\n")

print(f"audio {cues['duration']:.0f}s -> {out} ({os.path.getsize(out) // 1024} KB)")
